// sampleConfigDump mirrors the confirmed OrcaSlicer config-dump footer lines from a real
// sliced file (see plan: KITCHE~1.GCO), used across the parser tests below.
const sampleConfigDump = `
; generated by OrcaSlicer
; some_unrelated_setting = ignored
; filament_max_volumetric_speed = 18,16
; pressure_advance = 0.0264,0.02
; filament_flow_ratio = 0.95,0.95
; bridge_flow = 1
; bridge_density = 100%
; retraction_length = 0.7
; retraction_speed = 45
`

func TestParseCalibrationFromGcode_ToolIndex0(t *testing.T) {
	got := ParseCalibrationFromGcode([]byte(sampleConfigDump), 0)
	want := map[string]string{
		"cal_max_flow_rate":     "18",
		"cal_pressure_advance":  "0.0264",
		"cal_flow_ratio":        "0.95",
		"cal_bridge_flow_ratio": "1",
		"cal_bridge_density":    "100",
		"cal_retraction_length": "0.7",
		"cal_retraction_speed":  "45",
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s = %q, want %q", k, got[k], v)
		}
	}
	if len(got) != len(want) {
		t.Errorf("got %d keys, want %d: %v", len(got), len(want), got)
	}
}

func TestParseCalibrationFromGcode_ToolIndex1(t *testing.T) {
	got := ParseCalibrationFromGcode([]byte(sampleConfigDump), 1)
	// Per-extruder lists select index 1; bridge_flow/bridge_density are global
	// (not per-extruder) and must stay the same regardless of toolIndex.
	if got["cal_max_flow_rate"] != "16" {
		t.Errorf("cal_max_flow_rate = %q, want %q", got["cal_max_flow_rate"], "16")
	}
	if got["cal_pressure_advance"] != "0.02" {
		t.Errorf("cal_pressure_advance = %q, want %q", got["cal_pressure_advance"], "0.02")
	}
	if got["cal_flow_ratio"] != "0.95" {
		t.Errorf("cal_flow_ratio = %q, want %q", got["cal_flow_ratio"], "0.95")
	}
	if got["cal_bridge_flow_ratio"] != "1" {
		t.Errorf("cal_bridge_flow_ratio = %q, want %q", got["cal_bridge_flow_ratio"], "1")
	}
	if got["cal_bridge_density"] != "100" {
		t.Errorf("cal_bridge_density = %q, want %q", got["cal_bridge_density"], "100")
	}
}

func TestParseCalibrationFromGcode_OutOfRangeToolIndexFallsBackToZero(t *testing.T) {
	got := ParseCalibrationFromGcode([]byte(sampleConfigDump), 5)
	if got["cal_max_flow_rate"] != "18" {
		t.Errorf("cal_max_flow_rate = %q, want %q (fallback to index 0)", got["cal_max_flow_rate"], "18")
	}
	got2 := ParseCalibrationFromGcode([]byte(sampleConfigDump), -1)
	if got2["cal_max_flow_rate"] != "18" {
		t.Errorf("cal_max_flow_rate (negative index) = %q, want %q (fallback to index 0)", got2["cal_max_flow_rate"], "18")
	}
}

func TestParseCalibrationFromGcode_MissingKeysOmitted(t *testing.T) {
	got := ParseCalibrationFromGcode([]byte("; nothing_relevant = here\n"), 0)
	if len(got) != 0 {
		t.Errorf("expected no keys found, got %v", got)
	}
}

func TestParseCalibrationFromGcode_DoesNotMapInternalBridgeKeys(t *testing.T) {
	content := "; internal_bridge_flow = 1\n; internal_bridge_density = 100%\n; bridge_flow = 0.85\n; bridge_density = 90%\n"
	got := ParseCalibrationFromGcode([]byte(content), 0)
	if got["cal_bridge_flow_ratio"] != "0.85" {
		t.Errorf("cal_bridge_flow_ratio = %q, want %q (must match 'bridge_flow' not 'internal_bridge_flow')", got["cal_bridge_flow_ratio"], "0.85")
	}
	if got["cal_bridge_density"] != "90" {
		t.Errorf("cal_bridge_density = %q, want %q (must match 'bridge_density' not 'internal_bridge_density')", got["cal_bridge_density"], "90")
	}
}

