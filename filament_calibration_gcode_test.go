func newCalibrationTestBridge(t *testing.T, spoolmanURL string) *FilamentBridge {
	t.Helper()
	t.Setenv("THE_MOMENT_DB_PATH", t.TempDir())
	t.Setenv("THE_MOMENT_GCODE_PATH", t.TempDir())
	bridge, err := NewFilamentBridge(nil)
	if err != nil {
		t.Fatalf("NewFilamentBridge: %v", err)
	}
	t.Cleanup(func() { bridge.Close() })
	if spoolmanURL != "" {
		bridge.spoolman = NewSpoolmanClient(spoolmanURL, 5)
	}
	return bridge
}

// mockSpoolmanServer serves GetAllSpools/GetSpoolByID for spool ID 42, filament ID 7.
func mockSpoolmanServer(t *testing.T) *httptest.Server {
	t.Helper()
	filamentJSON := `{"id":7,"name":"PolyMax PLA","material":"PLA"}`
	spoolJSON := fmt.Sprintf(`{"id":42,"filament":%s}`, filamentJSON)
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		switch {
		case r.URL.Path == "/api/v1/spool":
			fmt.Fprintf(w, "[%s]", spoolJSON)
		case r.URL.Path == "/api/v1/spool/42":
			fmt.Fprint(w, spoolJSON)
		default:
			http.NotFound(w, r)
		}
	}))
}

func TestGetCalibrationCandidates_FindsPrintWithGcodeAttachment(t *testing.T) {
	srv := mockSpoolmanServer(t)
	defer srv.Close()
	b := newCalibrationTestBridge(t, srv.URL)

	res, err := b.db.Exec(`
		INSERT INTO print_history
			(printer_name, toolhead_id, spool_id, filament_used,
			 print_started, print_finished, job_name, status)
		VALUES ('Core One L', 0, 42, 5.0, datetime('now'), datetime('now'), 'calibration_test.gcode', 'completed')`)
	if err != nil {
		t.Fatalf("insert print_history: %v", err)
	}
	printID64, _ := res.LastInsertId()
	printID := int(printID64)

	if err := b.savePrintFile(printID, "gcode", "calibration_test.gcode", "", []byte(sampleConfigDump)); err != nil {
		t.Fatalf("savePrintFile: %v", err)
	}

	candidates, err := b.GetCalibrationCandidates(7)
	if err != nil {
		t.Fatalf("GetCalibrationCandidates: %v", err)
	}
	if len(candidates) != 1 {
		t.Fatalf("got %d candidates, want 1: %+v", len(candidates), candidates)
	}
	if candidates[0].PrintID != printID {
		t.Errorf("candidate PrintID = %d, want %d", candidates[0].PrintID, printID)
	}
	if candidates[0].PrinterName != "Core One L" {
		t.Errorf("candidate PrinterName = %q, want %q", candidates[0].PrinterName, "Core One L")
	}
}

