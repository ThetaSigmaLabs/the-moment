func TestGetCalibrationSource_ReadsAttachmentAndResolvesToolIndex(t *testing.T) {
	srv := mockSpoolmanServer(t)
	defer srv.Close()
	b := newCalibrationTestBridge(t, srv.URL)

	res, err := b.db.Exec(`
		INSERT INTO print_history
			(printer_name, toolhead_id, spool_id, filament_used,
			 print_started, print_finished, job_name, status)
		VALUES ('Core One L', 1, 42, 5.0, datetime('now'), datetime('now'), 'calibration_test.gcode', 'completed')`)
	if err != nil {
		t.Fatalf("insert print_history: %v", err)
	}
	printID64, _ := res.LastInsertId()
	printID := int(printID64)
	if err := b.savePrintFile(printID, "gcode", "calibration_test.gcode", "", []byte(sampleConfigDump)); err != nil {
		t.Fatalf("savePrintFile: %v", err)
	}

	content, toolIndex, err := b.GetCalibrationSource(7, printID)
	if err != nil {
		t.Fatalf("GetCalibrationSource: %v", err)
	}
	if toolIndex != 1 {
		t.Errorf("toolIndex = %d, want 1 (from print_history.toolhead_id)", toolIndex)
	}
	values := ParseCalibrationFromGcode(content, toolIndex)
	if values["cal_max_flow_rate"] != "16" {
		t.Errorf("cal_max_flow_rate = %q, want %q (toolIndex 1)", values["cal_max_flow_rate"], "16")
	}
}

